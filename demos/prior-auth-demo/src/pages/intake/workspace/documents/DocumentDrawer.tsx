import { Banner, Chip, DocumentSheet, Drawer } from "@/components/ui";
import type { IntakeDocument } from "@/data/intake/types";
import { stamp } from "@/lib/time";
import { ORIGIN_LABEL, originOf, TYPE_LABEL } from "./model";

/** A document in a drawer: its pages as the sheet draws them. Simulated content says so. */
export function DocumentDrawer({ doc, onClose }: { doc: IntakeDocument; onClose: () => void }) {
  return (
    <Drawer open onClose={onClose} title={doc.name} subtitle={`${TYPE_LABEL[doc.kind]} · ${ORIGIN_LABEL[originOf(doc)]} · ${stamp(doc.receivedAt)}`} width={720} right={doc.attach ? <Chip>Attached to the authorization</Chip> : undefined}>
      {doc.simulated ? <Banner tone="neutral" className="mb-4" title="Synthetic document">The content is simulated for the demo.</Banner> : null}
      {originOf(doc) === "generated" && !doc.simulated ? <Banner tone="mid" className="mb-4" title="Draft">Generated by Psyflo. A clinician reviews it before it is used.</Banner> : null}
      {doc.pages.map((p, i) => <DocumentSheet key={i} blocks={p} page={i + 1} pages={doc.pages.length} className="mb-4" />)}
    </Drawer>
  );
}
