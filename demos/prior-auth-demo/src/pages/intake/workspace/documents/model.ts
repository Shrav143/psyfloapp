import type { ModuleId } from "@/data/assess/types";
import type { IntakeDocument } from "@/data/intake/types";

/* Documents of an intake, classified for the Documents section: where each came from, what it is, and which module it supports. A document a person added
   carries its own `origin` and `moduleId`; older ones are read from their kind and name. Pure. */

export type DocOrigin = NonNullable<IntakeDocument["origin"]>;
export const ORIGIN_LABEL: Record<DocOrigin, string> = { referral: "Referral", uploaded: "Uploaded", generated: "Generated by Psyflo", authorization: "Authorization attachment" };

/** Who provided a document, in words: the referring organization for a referral document, otherwise how it came in. */
export function sourceOf(d: IntakeDocument, referralSource: string): string {
  const o = originOf(d);
  return o === "referral" ? referralSource : o === "uploaded" ? "Added by staff" : o === "generated" ? "Psyflo draft" : "Added for the authorization";
}
export const ORIGINS = Object.keys(ORIGIN_LABEL) as DocOrigin[];

export const TYPE_LABEL: Record<IntakeDocument["kind"], string> = {
  referral: "Referral", fax: "Fax", email: "Email", emr_summary: "EMR summary", school_report: "School report", discharge_summary: "Discharge summary", consent: "Consent", insurance_card: "Insurance card", other: "Document",
};
const REFERRAL_KINDS: IntakeDocument["kind"][] = ["referral", "fax", "email", "emr_summary", "school_report", "discharge_summary"];
const GENERATED_NAME = /^(AI Scribe transcript|Encounter note from the AI Scribe|Voice intake call|Clinical summary)/i;

export function originOf(d: IntakeDocument): DocOrigin {
  if (d.origin) return d.origin;
  if (GENERATED_NAME.test(d.name)) return "generated";
  return REFERRAL_KINDS.includes(d.kind) ? "referral" : "uploaded";
}

const BY_KIND: Partial<Record<IntakeDocument["kind"], ModuleId>> = {
  referral: "patient-referral", fax: "patient-referral", email: "patient-referral", insurance_card: "insurance", consent: "patient-referral",
  emr_summary: "clinical-history", discharge_summary: "clinical-history", school_report: "social-functional",
};
/** The module a document supports: the one a person linked, else the one its kind usually supports. */
export function moduleOf(d: IntakeDocument): ModuleId | undefined {
  if (d.moduleId) return d.moduleId;
  if (originOf(d) === "generated" && /transcript|note|call/i.test(d.name)) return "clinical-notes";
  return BY_KIND[d.kind];
}

export const countByOrigin = (docs: IntakeDocument[]): Record<DocOrigin | "all", number> => {
  const out: Record<DocOrigin | "all", number> = { all: docs.length, referral: 0, uploaded: 0, generated: 0, authorization: 0 };
  for (const d of docs) out[originOf(d)] += 1;
  return out;
};
