/** This clinic's own team for a service at the record's site. */
export function internalDestination(site: SiteId, serviceId: VaServiceId): ReferralDestination {
  const s = serviceById(serviceId);
  return {
    id: `internal-${site}-${serviceId}`, org: `This clinic, ${siteName(site)}: ${s.short} team`, kind: "internal", site, services: [serviceId], contact: "Program intake lead",
    channel: "internal", requiredDocs: ["Intake summary", "Release of information"], availability: s.status === "redesign" ? "not_yet" : "available",
    note: s.status === "redesign" ? "Can take a referral now for a start on or after July 1, 2027." : "Internal handoff within the clinic.",
  };
}

/** The external destinations that take a service (an external specialty program matches "external"). */
export const destinationsFor = (serviceId: VaServiceId | "external"): ReferralDestination[] => EXTERNAL_DESTINATIONS.filter((d) => d.services.includes(serviceId));
export const destinationById = (id: string): ReferralDestination | undefined => {
  const ext = EXTERNAL_DESTINATIONS.find((d) => d.id === id);
  if (ext) return ext;
  const m = /^internal-([AB])-(.+)$/.exec(id);
  return m ? internalDestination(m[1] as SiteId, m[2] as VaServiceId) : undefined;
};
